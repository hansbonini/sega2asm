package gfx

import (
	"image/color"

	"sega2asm/types"
)

func init() { types.RegisterGfxDecoder(bpp4{}) }

type bpp4 struct{}

func (bpp4) BPP() int          { return 4 }
func (bpp4) BytesPerTile() int { return 32 } // 64 pixels x 4 bits

func (bpp4) DefaultPalette() []color.RGBA {
	return []color.RGBA{
		{0x00, 0x00, 0x00, 0xFF}, // 0 - black (transparent)
		{0x22, 0x22, 0x22, 0xFF}, // 1
		{0x44, 0x44, 0x44, 0xFF}, // 2
		{0x66, 0x66, 0x66, 0xFF}, // 3
		{0x88, 0x88, 0x88, 0xFF}, // 4
		{0xAA, 0xAA, 0xAA, 0xFF}, // 5
		{0xCC, 0xCC, 0xCC, 0xFF}, // 6
		{0xEE, 0xEE, 0xEE, 0xFF}, // 7
		{0x11, 0x11, 0x11, 0xFF}, // 8
		{0x33, 0x33, 0x33, 0xFF}, // 9
		{0x55, 0x55, 0x55, 0xFF}, // A
		{0x77, 0x77, 0x77, 0xFF}, // B
		{0x99, 0x99, 0x99, 0xFF}, // C
		{0xBB, 0xBB, 0xBB, 0xFF}, // D
		{0xDD, 0xDD, 0xDD, 0xFF}, // E
		{0xFF, 0xFF, 0xFF, 0xFF}, // F
	}
}

// Decode decodes one 8x8 4bpp tile (Mega Drive native format).
// 32 bytes: each byte holds 2 pixels (4 bits each), high nibble first.
func (bpp4) Decode(tile []byte, set func(col, row, idx int)) {
	for row := 0; row < 8; row++ {
		for col := 0; col < 4; col++ {
			b := tile[row*4+col]
			set(col*2, row, int((b>>4)&0x0F))
			set(col*2+1, row, int(b&0x0F))
		}
	}
}
