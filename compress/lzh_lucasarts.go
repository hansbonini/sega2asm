type lzhDecoder struct {
	freq   [lzhT + 1]uint32
	prnt   [lzhT + lzhNChar]int
	son    [lzhT]int
	src    []byte
	pos    int
	getbuf uint32
	getlen int
}

func (v *lzhDecoder) getBit() int {
	for v.getlen <= 8 {
		var b uint32
		if v.pos < len(v.src) {
			b = uint32(v.src[v.pos])
			v.pos++
		}
		v.getbuf |= b << uint(8-v.getlen)
		v.getlen += 8
	}
	bit := int((v.getbuf & 0x8000) >> 15)
	v.getbuf <<= 1
	v.getlen--
	return bit
}

func (v *lzhDecoder) getByte() int {
	for v.getlen <= 8 {
		var b uint32
		if v.pos < len(v.src) {
			b = uint32(v.src[v.pos])
			v.pos++
		}
		v.getbuf |= b << uint(8-v.getlen)
		v.getlen += 8
	}
	b := int((v.getbuf & 0xff00) >> 8)
	v.getbuf <<= 8
	v.getlen -= 8
	return b
}

func (v *lzhDecoder) startHuff() {
	for i := 0; i < lzhNChar; i++ {
		v.freq[i] = 1
		v.son[i] = i + lzhT
		v.prnt[i+lzhT] = i
	}
	i, j := 0, lzhNChar
	for j <= lzhR {
		v.freq[j] = v.freq[i] + v.freq[i+1]
		v.son[j] = i
		v.prnt[i] = j
		v.prnt[i+1] = j
		i += 2
		j++
	}
	v.freq[lzhT] = 0xffff // sentinel
	v.prnt[lzhR] = 0
}

func (v *lzhDecoder) reconst() {
	// Compact leaf nodes into positions 0..N_CHAR-1, halving frequencies.
	j := 0
	for i := 0; i < lzhT; i++ {
		if v.son[i] >= lzhT {
			v.freq[j] = (v.freq[i] + 1) / 2
			v.son[j] = v.son[i]
			j++
		}
	}
	// Build internal nodes (insertion-sort into sorted freq array).
	// Invariant: f = freq[i]+freq[i+1] >= freq[i+1], so k >= i+2 always;
	// elements at positions 0..i+1 are never shifted.
	i := 0
	for ; j < lzhT; i, j = i+2, j+1 {
		f := v.freq[i] + v.freq[i+1]
		k := j - 1
		for f < v.freq[k] {
			k--
		}
		k++
		copy(v.freq[k+1:j+1], v.freq[k:j])
		v.freq[k] = f
		copy(v.son[k+1:j+1], v.son[k:j])
		v.son[k] = i
	}
	// Reconnect parent pointers.
	for i := 0; i < lzhT; i++ {
		k := v.son[i]
		if k >= lzhT {
			v.prnt[k] = i
		} else {
			v.prnt[k] = i
			v.prnt[k+1] = i
		}
	}
}

func (v *lzhDecoder) update(c int) {
	if v.freq[lzhR] == lzhMaxFreq {
		v.reconst()
	}
	c = v.prnt[c+lzhT]
	for {
		k := int(v.freq[c]) + 1
		v.freq[c] = uint32(k)
		l := c + 1
		if uint32(k) > v.freq[l] {
			// Find rightmost node with freq < k; freq[lzhT]=0xffff is sentinel.
			l++
			for uint32(k) > v.freq[l] {
				l++
			}
			l--
			// Swap subtrees of c and l.
			v.freq[c] = v.freq[l]
			v.freq[l] = uint32(k)
			i := v.son[c]
			v.prnt[i] = l
			if i < lzhT {
				v.prnt[i+1] = l
			}
			jj := v.son[l]
			v.son[l] = i
			v.prnt[jj] = c
			if jj < lzhT {
				v.prnt[jj+1] = c
			}
			v.son[c] = jj
			c = l
		}
		c = v.prnt[c]
		if c == 0 {
			break
		}
	}
}

func (v *lzhDecoder) decodeChar() int {
	c := v.son[lzhR]
	for c < lzhT {
		c += v.getBit()
		c = v.son[c]
	}
	c -= lzhT
	v.update(c)
	return c
}

func (v *lzhDecoder) decodePosition() int {
	i := v.getByte()
	c := int(lzhDCode[i]) << 6
	j := int(lzhDLen[i]) - 2
	for j > 0 {
		i = (i << 1) + v.getBit()
		j--
	}
	return c | (i & 0x3F)
}

// DecompressLZHLucasArts decompresses data using the LZH format used by LucasArts
// titles on the Sega Mega Drive. Adaptive Huffman + LZ sliding window (LZHUF variant).
//
// Header: BE16 uncompressed size.
// N=4096, F=60, THRESHOLD=2. Ring buffer pre-filled with 0x20 (space).
// Position encoded via fixed d_code/d_len tables (upper 6 bits) + inline lower 6 bits.
func DecompressLZHLucasArts(src []byte) ([]byte, error) {
	if len(src) < 2 {
		return nil, fmt.Errorf("lzhlucasarts: too short")
	}
	outputSize := int(binary.BigEndian.Uint16(src[0:2]))

	v := &lzhDecoder{src: src[2:]}
	v.startHuff()

	var textBuf [lzhN + lzhF - 1]byte
	for i := range textBuf[:lzhN-lzhF] {
		textBuf[i] = 0x20
	}
	r := lzhN - lzhF // = 4036

	out := make([]byte, 0, outputSize)
	for len(out) < outputSize {
		c := v.decodeChar()
		if c < 256 {
			out = append(out, byte(c))
			textBuf[r] = byte(c)
			r = (r + 1) & (lzhN - 1)
		} else {
			// Back-reference: c encodes match length.
			i := (r - v.decodePosition() - 1) & (lzhN - 1)
			matchLen := c - 255 + lzhThresh // c - 253
			for k := 0; k < matchLen; k++ {
				cb := textBuf[(i+k)&(lzhN-1)]
				out = append(out, cb)
				textBuf[r] = cb
				r = (r + 1) & (lzhN - 1)
			}
		}
	}
	return out, nil
}
