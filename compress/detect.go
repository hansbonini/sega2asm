// Detect scans rom for known compression routine signatures and returns all
// matches sorted by ROM offset. Each match names a compression algorithm
// accepted by Decompress.
//
// Post-processing removes overlapping matches: when a shorter signature
// match falls entirely within the byte range of a longer one, the shorter
// match is discarded.
func Detect(rom []byte) []Match {
	type candidate struct {
		Match
		sigLen int
	}
	var candidates []candidate
	for _, entry := range signatures {
		off := 0
		for {
			idx := bytes.Index(rom[off:], entry.sig)
			if idx < 0 {
				break
			}
			absOff := off + idx

			// Word-alignment filter: M68K code lives at even addresses.
			if entry.wordAligned && absOff%2 != 0 {
				off = absOff + 1
				continue
			}

			// Custom validator.
			if entry.validator != nil && !entry.validator(rom, absOff) {
				off = absOff + 1
				continue
			}

			candidates = append(candidates, candidate{
				Match:  Match{Name: entry.name, Offset: absOff},
				sigLen: len(entry.sig),
			})
			off = absOff + 1
		}
	}

	// Sort by offset, then longer signatures first (so the longer one wins).
	sort.Slice(candidates, func(i, j int) bool {
		if candidates[i].Offset != candidates[j].Offset {
			return candidates[i].Offset < candidates[j].Offset
		}
		return candidates[i].sigLen > candidates[j].sigLen
	})

	// Remove overlapping matches: if a candidate's byte range [off, off+len)
	// is fully contained within an already-accepted match, discard it.
	var accepted []candidate
	for _, c := range candidates {
		contained := false
		cEnd := c.Offset + c.sigLen
		for _, a := range accepted {
			aEnd := a.Offset + a.sigLen
			if c.Offset >= a.Offset && cEnd <= aEnd {
				contained = true
				break
			}
		}
		if !contained {
			accepted = append(accepted, c)
		}
	}

	matches := make([]Match, len(accepted))
	for i, a := range accepted {
		matches[i] = a.Match
	}
	sort.Slice(matches, func(i, j int) bool {
		return matches[i].Offset < matches[j].Offset
	})
	return matches
}
