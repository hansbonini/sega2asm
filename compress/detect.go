// Match reports a compression routine found in the ROM.
type Match struct {
	// Name is the compression identifier accepted by Decompress.
	Name string
	// Offset is the byte offset in the ROM where the routine signature begins.
	Offset int
}

// signature holds a detection entry. Fields beyond name/sig control matching
// to reduce false positives.
type signature struct {
	name string
	sig  []byte
	// wordAligned requires the match offset to be even (M68K instruction alignment).
	// Default true for code signatures; set false for data-magic signatures.
	wordAligned bool
	// validator is an optional callback that inspects surrounding bytes.
	// Return false to reject the candidate match.
	validator func(rom []byte, offset int) bool
}

